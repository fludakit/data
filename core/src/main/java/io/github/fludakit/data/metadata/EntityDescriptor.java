package io.github.fludakit.data.metadata;

import io.github.fludakit.data.metamodel.ElementCollectionAttribute;
import io.github.fludakit.data.metamodel.ForeignKeyAttribute;
import io.github.fludakit.data.metamodel.IdAttribute;
import io.github.fludakit.data.metamodel.OneToManyAttribute;
import jakarta.data.metamodel.Attribute;

import java.util.List;

/**
 * Acyclic, reflection-free description of an entity (or value object), built from the generated
 * Jakarta Data static metamodel: the accessors return the {@code _Entity} attribute field
 * instances themselves, so the same object is both the end-user's type-safe API
 * ({@code Order.by(_Profile.address.city.asc())}) and the engine's descriptor.
 *
 * <p>Classification is carried by the attribute's type, not an enum: {@code ColumnAttribute} for
 * scalar/leaf/foreign-key columns, {@code EmbeddedAttribute} for {@code @ValueObject} properties
 * (with the value object's own descriptor), and one-to-many / element-collection attributes for
 * relationships. This descriptor's role is relationship and column resolution; SQL rendering
 * consumes only the inherited {@link EntitySchema} view.</p>
 *
 * <p>{@link #attributes()} lists the ROOT-level members once — embedded and relation containers
 * included, flattened embedded leaves NOT. The embedded chain's leaves live on the generated
 * navigable metamodel classes, and the engine resolves any property path — local, embedded or
 * relation-traversing — through {@link #columnRef(String)}: the explicit {@link #columns()} view
 * (generated by the processor in declaration order) answers local and flattened-embedded paths, and
 * relation paths are walked through the container attributes' target descriptors.</p>
 *
 * @param <T> the entity type
 */
public interface EntityDescriptor<T> extends EntitySchema {

    Class<T> entityClass();

    /** Physical table name, or {@code null} for a value object. */
    @Override
    String tableName();

    /** The identifier attribute, or {@code null} for a value object. */
    IdAttribute<T> id();

    /**
     * All non-identifier attributes in declaration order: scalars, embedded containers, foreign
     * keys, one-to-many and element-collection relationships. Embedded leaves are NOT flattened in
     * here; they resolve through {@link #columnRef(String)}.
     */
    List<Attribute<T>> attributes();

    default boolean isValueObject() {
        return tableName() == null;
    }

    @Override
    default String idColumn() {
        return id() == null ? null : id().column();
    }

    /** Resolves a root-level attribute by name (the identifier first, then {@link #attributes()}). */
    default Attribute<T> attribute(String name) {
        if (id() != null && id().name().equals(name)) return id();
        for (Attribute<T> a : attributes()) {
            if (name.equals(a.name())) return a;
        }
        throw new IllegalArgumentException("Unknown property '" + name + "' on "
                + entityClass().getSimpleName());
    }

    /**
     * Extracts the runtime value of a dot path from {@code entity} WITHOUT reflection: generated
     * descriptors override this with a {@code switch} over the paths {@link #columnRef(String)}
     * resolves AT THE GENERATED DEPTH — one relation hop. Deeper paths are unknown to the switch and
     * throw {@link IllegalArgumentException}: a runtime deep path can sort under OFFSET paging yet
     * cannot produce a cursor key. Contract for overrides — a local, flattened-embedded or to-one leaf path returns the
     * single (possibly {@code null}) value; a path whose FIRST segment is a to-many (one-to-many or
     * element collection) returns the {@code List} of child leaf values (an empty list, never
     * {@code null}, when the collection is null/empty); an unknown path throws
     * {@link IllegalArgumentException}. The interface default throws
     * {@link UnsupportedOperationException} so a hand-rolled descriptor cannot be mistaken for a
     * value-capable one.
     */
    default Object value(String dotPath, Object entity) {
        throw new UnsupportedOperationException("descriptor " + getClass().getSimpleName()
                + " does not support value extraction");
    }

    /** Resolves a dot path — local, flattened embedded, or through a relation attribute — to its
     *  physical column plus contributed joins. Mirrored at compile time by the processor. */
    default ColumnRef columnRef(String path) {
        for (ColumnRef c : columns()) {
            if (c.path().equals(path)) return c;
        }
        int dot = path.indexOf('.');
        if (dot < 0) {
            throw new IllegalArgumentException("Unknown property '" + path + "' on "
                    + entityClass().getSimpleName());
        }
        String head = path.substring(0, dot);
        String rest = path.substring(dot + 1);
        Attribute<T> a = attribute(head);
        if (a instanceof ForeignKeyAttribute<?, ?> fk) {
            EntityDescriptor<?> target = fk.targetDescriptor().get();
            requireNavigable(target, head, path);
            return target.columnRef(rest).withPrefix(head,
                    new JoinRef(target.tableName(), head, fk.column(), target.idColumn()));
        }
        if (a instanceof OneToManyAttribute<?, ?> otm) {
            EntityDescriptor<?> target = otm.targetDescriptor().get();
            requireNavigable(target, head, path);
            return target.columnRef(rest).withPrefix(head,
                    new JoinRef(target.tableName(), head, idColumn(), otm.childFkColumn()));
        }
        if (a instanceof ElementCollectionAttribute<?, ?> ec) {
            EntityDescriptor<?> target = ec.elementDescriptor().get();
            requireNavigable(target, head, path);
            return target.columnRef(rest).withPrefix(head,
                    new JoinRef(ec.childTable(), head, idColumn(), ec.parentFkColumn()));
        }
        throw new IllegalArgumentException("Property '" + head + "' does not support path navigation"
                + " (path: " + path + ")");
    }

    private static void requireNavigable(EntityDescriptor<?> target, String head, String path) {
        if (target == null) {
            throw new IllegalArgumentException("Property '" + head
                    + "' targets an unmapped type and does not support path navigation"
                    + " (path: " + path + ")");
        }
    }
}
