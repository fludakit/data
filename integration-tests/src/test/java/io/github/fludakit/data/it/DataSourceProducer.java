package io.github.fludakit.data.it;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Produces;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.Connection;

@ApplicationScoped
public class DataSourceProducer {

    @Produces
    @ApplicationScoped
    public DataSource dataSource() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:it;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE");
        try (Connection c = ds.getConnection()) {
            for (String stmt : new String[]{
                    // Weld (re)starts a container per test method; the named in-memory database survives
                    // across containers (DB_CLOSE_DELAY=-1), so start each one from a clean schema.
                    "DROP ALL OBJECTS",
                    "CREATE TABLE customers (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), email VARCHAR(255))",
                    "CREATE TABLE products (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255), price DECIMAL(10,2))",
                    "CREATE TABLE \"orders\" (id BIGINT AUTO_INCREMENT PRIMARY KEY, amount DECIMAL(10,2), customer_id BIGINT)",
                    "CREATE TABLE order_items (order_id BIGINT, product_id BIGINT, quantity INT)",
                    "CREATE TABLE profiles (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " full_name VARCHAR(255),"
                            + " address_city VARCHAR(100), address_zip INTEGER,"
                            + " address_point_lat DOUBLE PRECISION, address_point_lng DOUBLE PRECISION)",
                    // CV (Profile) aggregate: the composition entity collections definition their own
                    // tables with the aggregate fk profile_id; the ContactPoint element collection
                    // lives in the child table contact_points (Names.childTable). "value"/"year"
                    // are H2 2.x reserved words — created quoted lowercase to match the generated
                    // quoted SQL.
                    "CREATE TABLE work_experiences (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " company VARCHAR(255), year_start INT, year_end INT, profile_id BIGINT)",
                    "CREATE TABLE educations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " institution VARCHAR(255), degree VARCHAR(255), \"year\" INT, profile_id BIGINT)",
                    "CREATE TABLE contact_points (profile_id BIGINT, kind VARCHAR(100), \"value\" VARCHAR(255))",
                    // Relationship-hydration corpus: Team.players (one-to-many, inverse fk
                    // team_id) and Player.team (many-to-one onto the same column).
                    "CREATE TABLE teams (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))",
                    "CREATE TABLE players (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100),"
                            + " team_id BIGINT)",
                    // Enum round-trip corpus: the enum persists as its name (VARCHAR) and the generated
                    // row mapper reads it back via Enum.valueOf.
                    "CREATE TABLE tasks (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255),"
                            + " status VARCHAR(50))",
                    // Composing to-one JOIN-projection corpus: Book.author is a bare entity field on an
                    // @AggregateRoot whose definition is managed, so the CRUD reads carry a LEFT JOIN to
                    // author and project its leaves under <field>_join_<column> labels.
                    "CREATE TABLE authors (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " name VARCHAR(100))",
                    "CREATE TABLE books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                            + " title VARCHAR(100), author_id BIGINT)"
            }) {
                c.createStatement().execute(stmt);
            }
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
        return ds;
    }
}
