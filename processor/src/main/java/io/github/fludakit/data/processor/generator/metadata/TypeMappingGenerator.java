/**
 * Emits {@code <Entity>Metadata}: the generated {@link TypeMapping} descriptor for one mapped type —
 * the column-name constants, {@code props()}, {@code columnRefs()}, {@code columns()}, the generated
 * {@code resolve(String)} switch and the reflection-free {@code ValueAccess.value(String, T)} switch.
 *
 * <p>The value objects a type embeds are generated by the same emitter, children before parents, so a
 * parent's {@code <VO>Metadata.INSTANCE} reference always names a class that exists. That is the one
 * cycle this emitter has to break: {@code A} embeds {@code B} embeds {@code A} is a legal declaration
 * shape, and the name is registered before recursing so the second visit is a no-op.</p>
 *
 * <p>Nothing here touches {@code Filer}: the source goes out through {@link RepositorySourceWriter},
 * which is also what registers the generated name. It holds no {@code Elements} either — resolving a
 * value-object element by name is {@link TypeModelResolver#elementFor(String)}, the one place a name
 * becomes a type, so a compile-time query no longer decides whether this emitter can be constructed.
 * A degraded path is reported through {@link Diagnostics}, which is swappable. The emitter never
 * reaches for {@code ProcessingEnvironment} itself.</p>
 */
public final class TypeMappingGenerator {

    private static final ClassName MD_COLUMN_REF =
            ClassName.get("io.github.fludakit.data.metadata", "ColumnRef");
    private static final ClassName MD_JOIN_EDGE =
            ClassName.get("io.github.fludakit.data.metadata", "JoinEdge");
    private static final ClassName MD_COLUMN_PLACEMENT =
            ClassName.get("io.github.fludakit.data.metadata", "ColumnPlacement");

    private final Diagnostics diagnostics;
    private final TypeModelResolver typeMappingBuilder;
    private final PathResolver pathResolver;
    private final RepositorySourceWriter sourceWriter;

    /**
     * The {@code <T>Metadata} name per mapped-type FQN. Shared by reference with the processor, which
     * reads it to wire row mappers and query builders to the descriptor; this class is its only writer.
     */
    private final Map<String, ClassName> metadataTypes;
    /** The reflection-free {@code ValueAccess.value(...)} emitter, split from the descriptor structure. */
    private final ValueAccessGenerator valueAccessGenerator;
    private final NavigationAnalysis navigationAnalysis;

    public TypeMappingGenerator(Diagnostics diagnostics, TypeModelResolver typeMappingBuilder,
                      PathResolver pathResolver, RepositorySourceWriter sourceWriter,
                      Map<String, ClassName> metadataTypes) {
        this.diagnostics = diagnostics;
        this.typeMappingBuilder = typeMappingBuilder;
        this.pathResolver = pathResolver;
        this.sourceWriter = sourceWriter;
        this.metadataTypes = metadataTypes;
        this.valueAccessGenerator = new ValueAccessGenerator(diagnostics, typeMappingBuilder);
        this.navigationAnalysis = new NavigationAnalysis();
    }

    /**
     * The {@code <T>Metadata} name for {@code element}, generating the descriptor — and, before it,
     * every value object transitively embedded in it — on first use.
     *
     * <p>Idempotent across rounds and safe against VO cycles: the name is already what
     * {@link #generateEmbeddedDescriptors} registers for a value object, so a second visit is a cache
     * hit. This is the only path that writes the {@code <T>Metadata} name, so a consumer that needs
     * the descriptor to exist asks here instead of poking the registry.</p>
     */
    public ClassName metadataFor(TypeElement element, TypeMapping<?> model) {
        String fqn = element.getQualifiedName().toString();
        ClassName known = metadataTypes.get(fqn);
        if (known != null) {
            return known;
        }
        generateEmbeddedDescriptors(model);
        ClassName type = generateMetadata(element, model);
        metadataTypes.put(fqn, type);
        return type;
    }

    /**
     * Emits {@code <Entity>Metadata implements TypeMapping<Entity>}: the column-name
     * constants (one per mapped property plus the table name) alongside the descriptor view —
     * {@code INSTANCE}, {@code tableName()}, {@code kind()}, {@code typeName()}, {@code id()} and
     * {@code attributes()} and {@code columnRefs()}. A value object (EMBEDDED target) has no table and no id, so its
     * TABLE_NAME constant is omitted and the matching accessors return {@code null}. An EMBEDDED
     * property contributes no constant of its own — its {@code column} slot holds a leaf prefix,
     * so no physical column named after the property exists — but each flattened leaf of its
     * value-object descriptor gets a constant {@code <PREFIX>_<LEAF>} named
     * {@code <prefix>_<leaf>} (nesting is resolved inside the descriptor, so one loop
     * per embedded attribute suffices). The accessor bodies return the {@code _Entity} metamodel
     * field instances when a metamodel was generated; a value object has none, so its
     * members are emitted as fresh attribute-record literals with the same shapes. Embedded leaves
     * are NOT flat {@code attributes()} members: the navigable metamodel classes carry them as
     * {@code *AttributeRecord} fields, and {@code columnRefs()} indexes their DOT PATHS to
     * {@code ColumnRef} placements. The two are different indexes of the same leaves and neither
     * holds the other — a placement is a column plus its owning table, while an attribute record is
     * a name plus a path and knows nothing about columns. The ordered
     * mapping index also supplies the inherited root-table {@code columns()} view.
     */
    public ClassName generateMetadata(TypeElement entityElement, TypeMapping<?> entity) {
        String packageName = typeMappingBuilder.classNameFor(entity.typeName()).packageName();
        String simpleName = entityElement.getSimpleName() + "Metadata";
        ClassName self = ClassName.get(packageName, simpleName);
        TypeName entityType = typeMappingBuilder.classNameFor(entity.typeName());
        ClassName descriptor = ClassName.get("io.github.fludakit.data.metadata", "TypeMapping");

        ClassName valueAccess = ClassName.get("io.github.fludakit.data.metadata", "ValueAccess");
        TypeSpec.Builder builder = TypeSpec.classBuilder(simpleName)
                .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
                .addSuperinterface(ParameterizedTypeName.get(descriptor, entityType))
                .addSuperinterface(ParameterizedTypeName.get(valueAccess, entityType))
                .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
                .addField(FieldSpec.builder(self, "INSTANCE", Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                        .initializer("new $T()", self).build());
        if (entity.tableName() != null) {
            builder.addField(Literals.stringConstant("TABLE_NAME", entity.tableName()));
        }
        if (entity.id() != null) {
            builder.addField(Literals.stringConstant(Literals.constName(entity.id().name()), entity.id().column()));
        }
        Set<String> embeddedNames = new HashSet<>();
        for (Prop a : entity.props()) {
            if (a instanceof Prop.Embedded) {
                embeddedNames.add(a.name());
            }
        }
        for (Prop p : entity.rowProps()) {
            if (!embeddedNames.contains(p.name())) {
                builder.addField(Literals.stringConstant(Literals.constName(p.name()), Props.column(p)));
            }
        }
        // flattened embedded leaves: one constant per physical leaf column. The
        // EMBEDDED property's own name stays skipped above — its column slot is only a leaf prefix —
        // while each leaf of the (already-flattened) value-object descriptor surfaces as
        // <prefix>_<leaf>, e.g. an embedded "point" yields POINT_LAT = "point_lat". The constant
        // NAME derives from the leaf's COLUMN (not the attribute name) so name and value agree
        // whenever the attribute name is not the snake case of its column.
        for (Prop a : entity.props()) {
            if (!(a instanceof Prop.Embedded embedded) || embedded.target() == null) {
                continue;
            }
            for (ColumnRef leaf : embedded.target().columns()) {
                builder.addField(Literals.stringConstant(
                        Names.toSnakeCase(Names.columnBase(embedded.name()) + "_" + leaf.column()).toUpperCase(),
                        Names.columnBase(embedded.name()) + "_" + leaf.column()));
            }
        }

        // The domain role is carried by WHICH TypeMapping this descriptor implements, not by a flag:
        // a root states that it owns the aggregate lifecycle, a plain entity stays on the interface
        // default. Only a root overrides, so a plain entity never claims a lifecycle it does not have.
        if (entity.ownsAggregateLifecycle()) {
            builder.addMethod(MethodSpec.methodBuilder("ownsAggregateLifecycle").addModifiers(Modifier.PUBLIC)
                    .addAnnotation(Override.class)
                    .returns(TypeName.BOOLEAN)
                    .addStatement("return true")
                    .build());
        }
        builder.addMethod(Literals.stringAccessor("tableName", entity.tableName()));
        builder.addMethod(Literals.stringAccessor("typeName", entity.typeName()));

        ClassName propId = descriptor.nestedClass("Prop").nestedClass("Id");
        Prop.Id idProp = entity.id();
        MethodSpec.Builder id = MethodSpec.methodBuilder("id").addModifiers(Modifier.PUBLIC)
                .addAnnotation(Override.class).returns(propId);
        if (idProp == null) {
            id.addStatement("return null");
        } else {
            id.addStatement("return new $T($S, $S, $S)", propId, idProp.name(), idProp.column(), idProp.typeFqn());
        }
        builder.addMethod(id.build());

        ClassName prop = descriptor.nestedClass("Prop");
        CodeBlock.Builder propsList = CodeBlock.builder().add("$T.of(", ClassName.get(java.util.List.class));
        boolean first = true;
        for (Prop p : entity.props()) {
            if (!first) {
                propsList.add(", ");
            }
            first = false;
            propsList.add(Literals.propLiteral(descriptor, p));
        }
        propsList.add(")");
        builder.addMethod(MethodSpec.methodBuilder("props").addModifiers(Modifier.PUBLIC)
                .addAnnotation(Override.class)
                .returns(ParameterizedTypeName.get(ClassName.get(java.util.List.class), prop))
                .addStatement("return $L", propsList.build()).build());

        // Two surfaces come out of the same traversal enumeration: columnRefs() is the entity's OWN
        // columns as placements, and resolve() is every path the entity can answer, including the
        // relation-traversing ones that need an edge. columnRefs() holds placements ONLY — a column
        // reached across an edge has no business in a map that cannot express the edge.
        List<NavCase> navs = navigationAnalysis.navCases(entityElement, entity);
        ClassName pathKey = ClassName.get(String.class);
        MethodSpec.Builder columnRefs = MethodSpec.methodBuilder("columnRefs").addModifiers(Modifier.PUBLIC)
                .addAnnotation(Override.class)
                .returns(ParameterizedTypeName.get(ClassName.get(java.util.Map.class),
                        pathKey, MD_COLUMN_REF))
                .addStatement("$T<$T, $T> mappings = new $T<>()",
                        ClassName.get(java.util.Map.class), pathKey, MD_COLUMN_REF,
                        ClassName.get(java.util.LinkedHashMap.class));
        for (Map.Entry<String, ColumnRef> mapping : entity.localColumnRefs().entrySet()) {
            columnRefs.addStatement("mappings.put($S, $L)", mapping.getKey(),
                    Literals.columnRefLiteral(mapping.getValue()));
        }
        columnRefs.addStatement("return $T.unmodifiableMap(mappings)",
                ClassName.get(java.util.Collections.class));
        builder.addMethod(columnRefs.build());

        ResolverParts resolver = resolverSwitch(entityElement, entity, navs);
        if (resolver != null) {
            for (FieldSpec constant : resolver.constants()) {
                builder.addField(constant);
            }
            builder.addMethod(resolver.method());
        }

        builder.addMethod(MethodSpec.methodBuilder("columns").addModifiers(Modifier.PUBLIC)
                .addAnnotation(Override.class)
                .returns(ParameterizedTypeName.get(ClassName.get(java.util.List.class), MD_COLUMN_REF))
                .addStatement("return $L", Literals.columnRefList(entity.columns()))
                .build());

        // the read-side twin of the column view. columns()/columnRefs() answer WHERE a dot
        // path lives; ValueAccess.value() answers what it IS on a materialised row, so a paged read can build its own
        // cursor key without reflection. Generation is NOTE-degraded: a descriptor that cannot carry the
        // switch simply keeps the interface default (which fails fast) instead of failing the round.
        MethodSpec valueMethod = valueAccessGenerator.valueMethod(entityElement, entity, navs);
        if (valueMethod != null) {
            builder.addMethod(valueMethod);
        }

        sourceWriter.write(packageName + "." + simpleName, entityElement,
                JavaFile.builder(packageName, builder.build()).skipJavaLangImports(true).build());
        return self;
    }

    /** The generated {@code resolve} method plus the {@code JoinEdge} constants its cases reference. */
    private record ResolverParts(MethodSpec method, List<FieldSpec> constants) { }

    /**
     * Emits {@code public ColumnPlacement resolve(String path)}: one {@code case} per path this entity
     * can answer, returning that path's placement — the terminal column plus the {@link JoinEdge}s
     * needed to reach it.
     *
     * <p>The navigation list is fixed at compile time, so this is a switch over the finite path set
     * instead of a runtime walk across {@code TypeMapping} instances: no map lookup per hop, no
     * cycle guard (cycles are impossible in a finite list), and no {@code ColumnRef} chain built just
     * to be unwrapped. An unknown path is already a generation-time exclusion; at runtime it throws,
     * as the walk did.</p>
     *
     * <p>Each relation head contributes ONE {@code private static final JoinEdge} constant shared by
     * every leaf reached through it. The constant carries its cardinality ({@code ToOne} /
     * {@code ToMany}), which the old {@code ColumnRef.Join} literal could not express.</p>
     *
     * @return the parts, or {@code null} when the entity resolves no path at all — the interface's
     *         generic walk then stays in force
     */
    private static ResolverParts resolverSwitch(TypeElement entityElement, TypeMapping<?> entity,
                                                List<NavCase> navs) {
        Map<String, ColumnRef> own = entity.localColumnRefs();
        if (own.isEmpty() && navs.isEmpty()) {
            return null;
        }
        // One constant per distinct relation head, keyed by the property name that crosses it.
        Map<String, JoinEdge> heads = new LinkedHashMap<>();
        for (NavCase nav : navs) {
            String head = nav.path().substring(0, nav.path().indexOf('.'));
            heads.putIfAbsent(head, nav.placement().edges().getFirst());
        }
        List<FieldSpec> constants = new ArrayList<>();
        Map<String, String> constantNames = new LinkedHashMap<>();
        for (Map.Entry<String, JoinEdge> head : heads.entrySet()) {
            String name = "EDGE_" + MemberNames.upperSnake(head.getKey());
            constantNames.put(head.getKey(), name);
            constants.add(FieldSpec.builder(MD_JOIN_EDGE, name, Modifier.PRIVATE, Modifier.STATIC,
                            Modifier.FINAL)
                    .initializer("$L", Literals.joinEdgeLiteral(head.getValue()))
                    .build());
        }
        MethodSpec.Builder resolve = MethodSpec.methodBuilder("resolve").addModifiers(Modifier.PUBLIC)
                .addAnnotation(Override.class)
                .returns(MD_COLUMN_PLACEMENT)
                .addParameter(String.class, "path");
        resolve.beginControlFlow("switch (path)");
        for (Map.Entry<String, ColumnRef> entry : own.entrySet()) {
            resolve.addStatement("case $S: return new $T($L)", entry.getKey(), MD_COLUMN_PLACEMENT,
                    Literals.columnRefLiteral(entry.getValue()));
        }
        for (NavCase nav : navs) {
            String head = nav.path().substring(0, nav.path().indexOf('.'));
            resolve.addStatement("case $S: return new $T($L, $T.of($L))", nav.path(), MD_COLUMN_PLACEMENT,
                    Literals.columnRefLiteral(nav.placement().leaf()),
                    ClassName.get(java.util.List.class), constantNames.get(head));
        }
        // The SAME type the runtime walk throws, so a caller can catch one exception for "this path is
        // not published" whether the descriptor was generated or the mapping is walking itself.
        resolve.addStatement("default: throw new $T(path, $S)", UnknownAttributePathException.class,
                entityElement.getQualifiedName().toString());
        resolve.endControlFlow();
        return new ResolverParts(resolve.build(), constants);
    }

    /**
     * Emits descriptor metadata for every value object transitively {@code EMBEDDED} in
     * {@code owner}'s attributes. Children are generated before their parent so the parent's
     * {@code <VO>Metadata.INSTANCE} reference resolves to a generated class; the
     * {@link #metadataTypes} guard is set before recursing, which bounds cycles (A embeds B embeds A).
     */
    public void generateEmbeddedDescriptors(TypeMapping<?> owner) {
        for (Prop a : owner.props()) {
            if (!(a instanceof Prop.Embedded embedded) || embedded.target() == null) {
                continue;
            }
            String voFqn = embedded.target().typeName();
            if (voFqn == null || metadataTypes.containsKey(voFqn)) {
                continue;
            }
            TypeElement voElement = typeMappingBuilder.elementFor(voFqn);
            if (voElement == null) {
                continue;
            }
            TypeMapping<?> voModel = typeMappingBuilder.descriptorFor(voElement);
            ClassName voName = typeMappingBuilder.classNameFor(voModel.typeName());
            metadataTypes.put(voFqn, ClassName.get(voName.packageName(), voName.simpleName() + "Metadata"));
            generateEmbeddedDescriptors(voModel);
            generateMetadata(voElement, voModel);
        }
    }
    /**
     * The {@code <VO>Metadata} type for a value-object (or relation-target) FQN: the registered name
     * from the embedded tree walk when available. The fallback resolves the element so a NESTED value
     * object ({@code pkg.Cfg.Geo}) maps to the TOP-LEVEL {@code pkg.GeoMetadata} the emitter actually
     * writes — the old last-dot split produced the member-class name {@code pkg.Cfg.GeoMetadata},
     * which never exists.
     */
    public ClassName metadataNameFor(String voFqn) {
        ClassName known = metadataTypes.get(voFqn);
        if (known != null) {
            return known;
        }
        String rawName = PathResolver.stripGenerics(voFqn);
        TypeElement element = typeMappingBuilder.elementFor(rawName);
        if (element != null) {
            ClassName resolved = ClassName.get(element);
            return ClassName.get(resolved.packageName(), resolved.simpleName() + "Metadata");
        }
        int dot = rawName.lastIndexOf('.');
        String pkg = dot < 0 ? "" : rawName.substring(0, dot);
        return ClassName.get(pkg, rawName.substring(dot + 1) + "Metadata");
    }

    /**
     * The navigation analysis behind the generated descriptor: which relation-traversing paths a
     * mapped type can answer, each with its resolved placement and the join edge that reaches it.
     * Nested here because the descriptor emitter is its only caller.
     */
    private final class NavigationAnalysis {

        List<NavCase> navCases(TypeElement entityElement, TypeMapping<?> entity) {
            TypeMapping<?> mapping = entity;
            List<NavCase> out = new ArrayList<>();
            for (Prop p : mapping.props()) {
                if (!PathResolver.isTraversable(p)) {
                    continue;
                }
                String targetFqn = Props.targetFqn(p);
                TypeMapping<?> target = pathResolver.descriptorByFqn(targetFqn);
                TypeElement targetElement = target == null ? null
                        : typeMappingBuilder.elementFor(PathResolver.stripGenerics(target.typeName()));
                String headGetter = MemberNames.getter(p.name());
                if (targetElement == null || !typeMappingBuilder.hasMethod(entityElement, headGetter)) {
                    continue; // an unmapped target or a bean-less head is unnavigable at runtime as well
                }
                CodeBlock head = CodeBlock.of("e.$L()", headGetter);
                boolean toOne = p instanceof Prop.Reference;
                TypeMapping<?> localTarget;
                JoinEdge edge;
                if (p instanceof Prop.ElementCollection elementCollection) {
                    localTarget = elementCollection.target();
                    edge = JoinEdges.toManyOrNull(mapping.tableName(), mapping.idColumn(),
                            elementCollection.childTable(), elementCollection.parentFkColumn());
                    if (edge == null) {
                        continue; // a child table / parent fk still unresolved: nothing to join from
                    }
                } else {
                    localTarget = target;
                    edge = referenceOrListJoin(p, mapping, target);
                    if (edge == null) {
                        continue; // unbuildable join: the compile paths unresolvedRelation drop
                    }
                }
                for (Map.Entry<String, ColumnRef> leaf : localTarget.localColumnRefs().entrySet()) {
                    out.add(new NavCase(p.name() + "." + leaf.getKey(),
                            new ColumnPlacement(leaf.getValue(), List.of(edge)),
                            targetElement, localTarget, head, toOne));
                }
            }
            return out;
        }

        private JoinEdge referenceOrListJoin(Prop prop, TypeMapping<?> owner, TypeMapping<?> target) {
            if (prop instanceof Prop.Reference ref) {
                if (target == null || target.tableName() == null || target.idColumn() == null) {
                    return null;
                }
                return JoinEdges.toOneOrNull(owner.tableName(), ref.fkColumn(),
                        target.tableName(), target.idColumn());
            }
            if (prop instanceof Prop.EntityCollection list) {
                if (target == null || target.tableName() == null || list.inverseFkColumn() == null
                        || owner.idColumn() == null) {
                    return null;
                }
                String childTable = list.targetTable() != null ? list.targetTable() : target.tableName();
                return JoinEdges.toManyOrNull(owner.tableName(), owner.idColumn(),
                        childTable, list.inverseFkColumn());
            }
            return null;
        }
    }
}
