/**
 * The composing to-one JOIN projection: instead of re-reading a to-one target with a second query,
 * the read LEFT JOINs it once and carries its flattened columns on the parent's own row.
 *
 * <p>Two artefacts come out of that decision and they must agree, which is why they are generated by
 * one class:</p>
 *
 * <ul>
 *   <li>the extra SELECT list ({@link #joinedProjection}) — each target column qualified by the join
 *       alias and re-labelled {@code <field>_join_<column>};</li>
 *   <li>the per-method row mapper ({@link #buildFullMapper}) — which reads exactly those labels back,
 *       delegating the root columns to the entity's own mapper and overwriting each traversed target
 *       with a fully populated instance.</li>
 * </ul>
 *
 * <p>Projection is depth-1 on purpose: a target's own references are neither selected nor read, so a
 * nested association stays null. A to-one join adds at most one row per parent, so it cannot fan out
 * and cannot move LIMIT or COUNT onto join rows — which is precisely why to-one is safe to project and
 * to-many is not.</p>
 *
 * <p>Shared by two callers: {@link RepositoryProcessor} asks for the mapper the inherited CRUD reads
 * use, and {@link RepositoryMethodCompiler} asks for the per-method one a query-by-names read needs
 * when its predicate or sort traverses a reference.</p>
 */
public final class JoinedProjectionEmitter {

    private final MappedTypeBuilder typeMappingBuilder;
    private final SqlDialect sqlDialect;

    public JoinedProjectionEmitter(MappedTypeBuilder typeMappingBuilder, SqlDialect sqlDialect) {
        this.typeMappingBuilder = typeMappingBuilder;
        this.sqlDialect = sqlDialect;
    }

    /**
     * The distinct {@link Prop.Reference} heads whose resolved predicate/sort refs carry a join (i.e. the
     * path traversed a Reference rather than an {@code EntityCollection}/{@code ElementCollection}). A joined ref's
     * path is {@code <head>.<leafPath>} (set by {@code withPrefix}); the head names the traversed
     * property. Composition and association references both qualify — the field is filled from the join
     * either way. Deduped by property name so one traversal of a shared head yields one projection.
     */
    public List<Prop.Reference> collectTraversedReferences(TypeMapping<?> mapping,
                                                            List<ColumnPlacement> predicateRefs,
                                                            List<ColumnPlacement> sortRefs) {
        List<Prop.Reference> out = new ArrayList<>();
        List<ColumnPlacement> all = new ArrayList<>(predicateRefs);
        all.addAll(sortRefs);
        for (ColumnPlacement ref : all) {
            if (ref.local()) {
                continue;
            }
            // The head edge's child table is the referenced entity's table; recover the matching
            // Prop.Reference from it (the ColumnRef no longer carries the property name). The head
            // may be a to-one Reference edge or a to-many Collection edge, so ask the edge for
            // its child table rather than assuming a case.
            String childTable = childTableOf(ref.edges().get(0));
            if (childTable == null) {
                continue;
            }
            for (Prop prop : mapping.props()) {
                if (prop instanceof Prop.Reference reference
                        && childTable.equals(reference.targetTable())) {
                    boolean seen = out.stream().anyMatch(r -> r.name().equals(reference.name()));
                    if (!seen) {
                        out.add(reference);
                    }
                    break;
                }
            }
        }
        return out;
    }

    /** The table an edge joins INTO. Every {@link JoinEdge} knows its child table, whichever case. */
    private static String childTableOf(JoinEdge edge) {
        return edge.childTable();
    }

    /**
     * The extra SELECT fragments a joined full-materialisation read needs: every flattened column of
     * each traversed target EXCEPT its own references (nested associations stay null, depth-1), qualified
     * by the join alias and re-labelled {@code <alias>_join_<column>} so the read is unambiguous against
     * the root's own columns. Emitted in the target's {@code columns()} declaration order.
     */
    public String joinedProjection(TypeMapping<?> mapping, List<Prop.Reference> traversed) {
        StringBuilder sb = new StringBuilder();
        for (Prop.Reference ref : traversed) {
            TypeMapping<?> targetModel = typeMappingBuilder.descriptorFor(ref.targetTypeName());
            if (targetModel == null) {
                continue;
            }
            // The join is aliased by the TARGET TABLE, not by the property that names it — a property
            // called `primary` whose target table is `child` joins "child" AS "child", so qualifying
            // the projected column by the property name would point at a table that is not in the
            // statement. The LABEL keeps the property name, so two references into one table still
            // produce distinct labels.
            String alias = ref.targetTable() != null ? ref.targetTable() : ref.name();
            for (Map.Entry<String, ColumnRef> entry : targetModel.localColumnRefs().entrySet()) {
                ColumnRef column = entry.getValue();
                String head = entry.getKey().contains(".")
                        ? entry.getKey().substring(0, entry.getKey().indexOf('.')) : entry.getKey();
                if (PathResolver.propOrNull(targetModel, head) instanceof Prop.Reference) {
                    continue; // nested association fk not selected — its target stays null (depth-1)
                }
                String qualified = qualifiedColumn(alias, column.column());
                String label = ref.name() + "_join_" + column.column();
                if (sb.length() > 0) {
                    sb.append(", ");
                }
                sb.append(qualified).append(" AS ").append(sqlDialect.quoteIdentifier(label));
            }
        }
        return sb.toString();
    }

    /**
     * Generates the per-method full mapper {@code mapRow_full_<method>}: it delegates the root columns to
     * the entity's generated row mapper (which already materialises non-traversed associations as
     * id-only partials) and then OVERWRITES each traversed association with a fully-populated instance
     * read from the {@code <alias>_join_<column>} labels. Primitive leaves use the temp+wasNull rule.
     * Reflection-free (Java 17 instanceof-chain).
     */
    public MethodSpec buildFullMapper(String mapperName, TypeMapping<?> entity, ClassName mapperType,
                               List<Prop.Reference> traversed) {
        TypeName entityType = typeMappingBuilder.classNameFor(entity.typeName());
        MethodSpec.Builder m = MethodSpec.methodBuilder(mapperName)
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(entityType)
                .addParameter(ClassName.get("java.sql", "ResultSet"), "rs")
                .addParameter(int.class, "rowNum")
                .addException(ClassName.get("java.sql", "SQLException"))
                .addStatement("$T entity = new $T().mapRow(rs, rowNum)", entityType, mapperType);
        for (Prop.Reference ref : traversed) {
            TypeMapping<?> targetModel = typeMappingBuilder.descriptorFor(ref.targetTypeName());
            if (targetModel == null || targetModel.id() == null) {
                continue;
            }
            TypeName idType = typeMappingBuilder.memberType(targetModel.typeName(), targetModel.id().name()).box();
            String idLabel = ref.name() + "_join_" + targetModel.id().column();
            String idLocal = ref.name() + "_join_id";
            m.addStatement("$T $L = rs.getObject($S, $T.class)", idType, idLocal, idLabel, idType);
            m.beginControlFlow("if ($L != null)", idLocal);
            String var = ref.name() + "Full";
            m.addStatement("$T $L = new $T()", typeMappingBuilder.classNameFor(targetModel.typeName()), var,
                    typeMappingBuilder.classNameFor(targetModel.typeName()));
            m.addStatement("$L.$L($L)", var, MemberNames.setter(targetModel.id().name()), idLocal);
            appendJoinedTargetLeaves(m, targetModel, ref.name(), var, entity.typeName().toString());
            m.addStatement("entity.$L($L)", MemberNames.setter(ref.name()), var);
            m.endControlFlow();
        }
        m.addStatement("return entity");
        return m.build();
    }

    /**
     * Fills the scalar and embedded-leaf columns of a joined target (its id was already set by the
     * caller). References in the target are skipped (nested associations stay null — depth-1) and the
     * target's own id is skipped (already assigned). Reads use {@code <alias>_join_<column>} labels,
     * exactly matching {@link #joinedProjection}; primitives follow the temp+wasNull rule.
     */
    private void appendJoinedTargetLeaves(MethodSpec.Builder builder, TypeMapping<?> valueObject, String alias, String targetVar,
                                          String ownerName) {
        for (Prop p : valueObject.rowProps()) {
            if (p instanceof Prop.Reference) {
                continue;
            }
            if (p instanceof Prop.Embedded embedded) {
                appendJoinedEmbedded(builder, embedded, alias, targetVar, ownerName);
                continue;
            }
            String label = alias + "_join_" + Props.column(p);
            if (!typeMappingBuilder.memberType(valueObject.typeName(), p.name()).isPrimitive()) {
                builder.addStatement("$L.$L(rs.getObject($S, $T.class))", targetVar, MemberNames.setter(p.name()), label, typeMappingBuilder.memberType(valueObject.typeName(), p.name()).box());
                continue;
            }
            String temp = alias + "_" + Props.column(p) + "Value";
            builder.addStatement("$T $L = rs.$L($S)", typeMappingBuilder.memberType(valueObject.typeName(), p.name()), temp, RowReads.primitiveGetter(alias + "." + p.name(), typeMappingBuilder.memberType(valueObject.typeName(), p.name())), label);
            builder.beginControlFlow("if (rs.wasNull())");
            builder.addStatement("throw new $T($S)", ClassName.get("java.sql", "SQLException"),
                    "NULL value in non-nullable primitive column \"" + label + "\" mapped to "
                            + ownerName + "." + alias + "." + p.name());
            builder.endControlFlow();
            builder.addStatement("$L.$L($L)", targetVar, MemberNames.setter(p.name()), temp);
        }
    }

    /** Reconstructs one embedded value-object of a joined target from its aliased leaf labels (per-subtree presence). */
    private void appendJoinedEmbedded(MethodSpec.Builder builder, Prop.Embedded embedded, String alias, String targetVar,
                                      String ownerName) {
        TypeMapping<?> vo = embedded.target();
        if (vo == null) {
            return;
        }
        String childVar = targetVar + MemberNames.capitalize(embedded.name());
        List<String> presence = new ArrayList<>();
        readJoinedEmbeddedLeaves(builder, vo, alias + "_join_" + Names.columnBase(embedded.name()), childVar, presence,
                ownerName + "." + alias + "." + embedded.name());
        boolean guarded = !presence.isEmpty();
        if (guarded) {
            builder.beginControlFlow("if ($L)", String.join(" || ", presence));
        }
        buildJoinedEmbeddedValue(builder, vo, alias + "_join_" + Names.columnBase(embedded.name()), childVar);
        builder.addStatement("$L.$L($L)", targetVar, MemberNames.setter(embedded.name()), childVar);
        if (guarded) {
            builder.endControlFlow();
        }
    }

    private void readJoinedEmbeddedLeaves(MethodSpec.Builder builder, TypeMapping<?> valueObject, String prefix, String local,
                                          List<String> presence, String path) {
        for (Prop p : valueObject.rowProps()) {
            if (p instanceof Prop.Reference) {
                continue;
            }
            if (p instanceof Prop.Embedded) {
                readJoinedEmbeddedLeaves(builder, ((Prop.Embedded) p).target(), prefix + "_" + Props.column(p),
                        local + MemberNames.capitalize(p.name()), presence, path + "." + p.name());
                continue;
            }
            String leafLocal = prefix + "_" + Props.column(p);
            if (!typeMappingBuilder.memberType(valueObject.typeName(), p.name()).isPrimitive()) {
                builder.addStatement("$T $L = rs.getObject($S, $T.class)", typeMappingBuilder.memberType(valueObject.typeName(), p.name()).box(), leafLocal, leafLocal,
                        typeMappingBuilder.memberType(valueObject.typeName(), p.name()).box());
                presence.add(leafLocal + " != null");
                continue;
            }
            builder.addStatement("$T $L = rs.$L($S)", typeMappingBuilder.memberType(valueObject.typeName(), p.name()), leafLocal, RowReads.primitiveGetter(path, typeMappingBuilder.memberType(valueObject.typeName(), p.name())), leafLocal);
            builder.beginControlFlow("if (rs.wasNull())");
            builder.addStatement("throw new $T($S)", ClassName.get("java.sql", "SQLException"),
                    "NULL value in non-nullable primitive column \"" + leafLocal + "\" mapped to " + path);
            builder.endControlFlow();
        }
    }

    private void buildJoinedEmbeddedValue(MethodSpec.Builder builder, TypeMapping<?> valueObject, String prefix, String local) {
        builder.addStatement("$T $L = new $T()", typeMappingBuilder.classNameFor(valueObject.typeName()), local,
                    typeMappingBuilder.classNameFor(valueObject.typeName()));
        for (Prop p : valueObject.rowProps()) {
            if (p instanceof Prop.Reference || p instanceof Prop.Embedded) {
                continue;
            }
            builder.addStatement("$L.$L($L)", local, MemberNames.setter(p.name()), prefix + "_" + Props.column(p));
        }
        for (Prop p : valueObject.rowProps()) {
            if (!(p instanceof Prop.Embedded)) {
                continue;
            }
            String childLocal = local + MemberNames.capitalize(p.name());
            List<String> terms = new ArrayList<>();
            RowReads.collectPresenceTerms(((Prop.Embedded) p).target(), prefix + "_" + Props.column(p),
                    terms, typeMappingBuilder::memberType);
            if (terms.isEmpty()) {
                buildJoinedEmbeddedValue(builder, ((Prop.Embedded) p).target(), prefix + "_" + Props.column(p), childLocal);
                builder.addStatement("$L.$L($L)", local, MemberNames.setter(p.name()), childLocal);
            } else {
                builder.beginControlFlow("if ($L)", String.join(" || ", terms));
                buildJoinedEmbeddedValue(builder, ((Prop.Embedded) p).target(), prefix + "_" + Props.column(p), childLocal);
                builder.addStatement("$L.$L($L)", local, MemberNames.setter(p.name()), childLocal);
                builder.endControlFlow();
            }
        }
    }

    /** The single {@code "qualifier"."column"} rendering a projected column is qualified with. */
    private String qualifiedColumn(String qualifier, String column) {
        return sqlDialect.quoteIdentifier(qualifier) + "." + sqlDialect.quoteIdentifier(column);
    }
}
